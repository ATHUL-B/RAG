"""Common English function words. Small on purpose: domain words (e.g. "net", "total")
are kept, and BM25's IDF already down-weights frequent terms."""


def analyze(text: str) -> list[str]:
    """Lowercase, normalize numbers (``1,577`` → ``1577``), tokenize, drop stop words."""
    normalized = _THOUSANDS_SEPARATOR.sub("", text.lower())
    return [token for token in _TOKEN.findall(normalized) if token not in STOP_WORDS]
